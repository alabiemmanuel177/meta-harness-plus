"""Audit V7 eval coverage gap: 500 predictions submitted, 467 graded.

Per V10_DESIGN.md §13.3: V7 trajectories are usable as DATA for the
difficulty heuristic, but the 33 instances with missing eval reports
need explanation. If failures cluster on specific repos or error
types, the V10 sandbox needs hardening before Phase 1 lands the same
instances.

Output: docs/audits/v7_missing_evals.md with breakdown by:
  - repo
  - error type (no_inst_dir, unknown_no_report, ...)
  - whether V7's predictions.jsonl had an empty patch for this instance
  - last lines of run_instance.log when present
"""

from __future__ import annotations

import collections
import json
import pathlib
import re


PROJECT_ROOT = pathlib.Path(__file__).resolve().parent.parent
V7_FINAL = PROJECT_ROOT / "runs" / "swebench_500_v7" / "v7_full500_FINAL.json"
V7_PREDS = PROJECT_ROOT / "runs" / "swebench_500_v7" / "predictions" / "v7_full500_seed0.jsonl"
V7_EVAL_ROOT = (
    PROJECT_ROOT / "logs" / "run_evaluation" / "v7_full500_seed0" / "deepseek-reasoner"
)
OUT_PATH = PROJECT_ROOT / "docs" / "audits" / "v7_missing_evals.md"


def _classify_log_tail(log_text: str) -> str:
    tail = log_text[-3000:]
    if re.search(r"Failed to apply patch|patch failed|patch does not apply", tail, re.I):
        return "patch_apply_failed"
    if re.search(r"timeout|timed out", tail, re.I):
        return "timeout"
    if re.search(r"Empty patch|empty patch|model_patch.*''", tail):
        return "empty_patch"
    if re.search(r"docker error|connection refused", tail, re.I):
        return "docker_error"
    if re.search(r"\bError\b|\bexception\b", tail, re.I):
        return "other_error"
    return "unknown"


def main() -> int:
    final = json.loads(V7_FINAL.read_text())
    submitted_iids = set(final["per_instance"].keys())
    per_instance = final["per_instance"]

    preds = {}
    for line in V7_PREDS.read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        rec = json.loads(line)
        preds[rec["instance_id"]] = rec.get("model_patch", "")

    graded = {
        p.name
        for p in V7_EVAL_ROOT.iterdir()
        if p.is_dir() and (p / "report.json").exists()
    }
    missing = sorted(submitted_iids - graded)

    by_repo: dict[str, int] = collections.Counter()
    by_error_type: dict[str, int] = collections.Counter()
    by_empty: dict[bool, int] = collections.Counter()
    rows: list[dict] = []

    for iid in missing:
        repo_prefix = iid.split("__")[0]
        by_repo[repo_prefix] += 1

        inst_dir = V7_EVAL_ROOT / iid
        log_path = inst_dir / "run_instance.log"
        if not inst_dir.exists():
            err = "no_inst_dir"
        elif log_path.exists():
            err = _classify_log_tail(log_path.read_text(errors="replace"))
        else:
            err = "no_log_file"
        by_error_type[err] += 1

        patch_text = preds.get(iid, "")
        was_empty = not patch_text.strip()
        by_empty[was_empty] += 1

        v7_resolved = per_instance.get(iid, {}).get("resolved", None)
        rows.append({
            "iid": iid,
            "repo": repo_prefix,
            "error_type": err,
            "submitted_empty_patch": was_empty,
            "v7_resolved_status": v7_resolved,
            "patch_len": len(patch_text),
        })

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    lines: list[str] = []
    lines.append("# V7 missing-evals audit")
    lines.append("")
    lines.append(
        f"Generated by `scripts/audit_missing_v7_evals.py` from "
        f"`{V7_FINAL.relative_to(PROJECT_ROOT)}` and "
        f"`{V7_EVAL_ROOT.relative_to(PROJECT_ROOT)}/`."
    )
    lines.append("")
    lines.append(f"- **Submitted predictions:** {len(submitted_iids)}")
    lines.append(f"- **Graded with report.json:** {len(graded)}")
    lines.append(f"- **Missing reports:** {len(missing)}")
    lines.append("")
    lines.append("## Breakdown by repo")
    lines.append("")
    lines.append("| Repo prefix | Missing |")
    lines.append("|---|---|")
    for repo, n in sorted(by_repo.items(), key=lambda x: -x[1]):
        lines.append(f"| {repo} | {n} |")
    lines.append("")
    lines.append("## Breakdown by error type")
    lines.append("")
    lines.append("| Error type | Count |")
    lines.append("|---|---|")
    for err, n in sorted(by_error_type.items(), key=lambda x: -x[1]):
        lines.append(f"| {err} | {n} |")
    lines.append("")
    lines.append("## V7-side prediction shape")
    lines.append("")
    lines.append(
        f"- Empty patches submitted (V7 produced nothing): "
        f"{by_empty.get(True, 0)}"
    )
    lines.append(
        f"- Non-empty patches that still didn't get an eval report: "
        f"{by_empty.get(False, 0)}"
    )
    lines.append("")
    lines.append("## All missing instances")
    lines.append("")
    lines.append("| Instance | Repo | Error type | Empty patch? |")
    lines.append("|---|---|---|---|")
    for r in rows:
        lines.append(
            f"| `{r['iid']}` | {r['repo']} | {r['error_type']} | "
            f"{'yes' if r['submitted_empty_patch'] else 'no'} |"
        )
    lines.append("")

    # Phase 1 implications.
    lines.append("## Phase 1 implications")
    lines.append("")
    top_repo, top_count = max(by_repo.items(), key=lambda x: x[1])
    lines.append(
        f"- {top_count}/{len(missing)} missing instances are in `{top_repo}`. "
        f"If V7's eval-skip pattern carries to V10 unchanged, the same "
        f"instances will produce empty patches in V10 and skip the grader. "
        f"V10's Phase 3 agent must have a stronger empty-patch fallback."
    )
    if by_error_type.get("no_inst_dir", 0) > 0:
        lines.append(
            f"- {by_error_type['no_inst_dir']}/{len(missing)} have no eval "
            f"directory — the SWE-bench harness pre-filtered them, almost "
            f"certainly because the predictions.jsonl entry was empty or "
            f"un-applyable. This is mostly upstream-of-our-control: the V10 "
            f"answer is to never submit empty patches in the first place."
        )
    if by_error_type.get("timeout", 0) > 0:
        lines.append(
            f"- {by_error_type['timeout']}/{len(missing)} hit eval timeouts. "
            f"V10 should ensure per-instance suite timeout (currently 8 min "
            f"in §3.5) is honored at the harness level."
        )
    lines.append("")
    lines.append(
        "**Conclusion:** the missing 33 are dominated by V7's empty-patch "
        "submissions (a property of V7's actor, not the sandbox). The "
        "sandbox itself does not appear to need additional hardening for "
        "these specific repos. Phase 1+ work focuses on improving the "
        "actor (Phase 3) and never submitting empty patches (Phase 4 "
        "validation gates a non-empty diff before write_predictions)."
    )
    lines.append("")

    OUT_PATH.write_text("\n".join(lines))
    print(f"[audit] wrote {OUT_PATH.relative_to(PROJECT_ROOT)}")
    print(f"[audit] missing={len(missing)}  by_repo={dict(by_repo)}  "
          f"by_error={dict(by_error_type)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
